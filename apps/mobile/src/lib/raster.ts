// ── Композиция полей ─────────────────────────────────────────

export function blank(width: number): string {
  return ".".repeat(width)
}

export function center(row: string, width: number): string {
  const pad = width - row.length
  if (pad <= 0) return row.slice(0, width)
  const left = Math.floor(pad / 2)
  return ".".repeat(left) + row + ".".repeat(pad - left)
}

/**
 * Рабочий дисплей главной: число сверху, питомец под ним,
 * остальное поле — выключенные точки.
 */
export function heroRows(
  value: string,
  creature: Raster,
  width: number,
  rows: number,
): string[] {
  const out: string[] = [blank(width)]
  digits(value).forEach((row) => out.push(center(row, width)))
  out.push(blank(width), blank(width), blank(width))
  creature.forEach((row) => out.push(center(row, width)))
  while (out.length < rows) out.push(blank(width))
  return out.slice(0, rows)
}

// ── Сигнальный режим: точки переменного диаметра ─────────────

/** 0 — пусто, 1 — сетка, … 5 — объект. */
export type Amplitude = 0 | 1 | 2 | 3 | 4 | 5

const AMPLITUDE_RATIO: Record<Amplitude, number> = {
  0: 0, 1: 0.20, 2: 0.34, 3: 0.52, 4: 0.74, 5: 0.96,
}

export function amplitudeRatio(level: Amplitude): number {
  return AMPLITUDE_RATIO[level]
}

/** Детерминированный шум: одно и то же поле на всех устройствах. */
function ambient(row: number, col: number): Amplitude {
  const v = Math.abs(Math.sin(row * 12.9898 + col * 78.233) * 43758.5453) % 1
  if (v < 0.58) return 1
  if (v < 0.84) return 2
  return 3
}

/**
 * Поле сигнального экрана: питомец крупными точками,
 * фон — модулированная мелким шумом сетка.
 */
export function signalField(
  creature: Raster,
  width: number,
  rows: number,
  top: number,
): Amplitude[][] {
  const left = Math.floor((width - (creature[0]?.length ?? 0)) / 2)
  const out: Amplitude[][] = []
  for (let r = 0; r < rows; r++) {
    const line: Amplitude[] = []
    for (let c = 0; c < width; c++) {
      const ar = r - top
      const ac = c - left
      const inside = ar >= 0 && ar < creature.length && ac >= 0 && ac < (creature[0]?.length ?? 0)
      line.push(inside && creature[ar]![ac] === "#" ? 5 : ambient(r, c))
    }
    out.push(line)
  }
  return out
}
