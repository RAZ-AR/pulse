/**
 * Формы эволюции по порогу баллов за всё время. От старшей к младшей.
 * Имена живут в i18n под ключом `pet.<id>` — здесь только данные.
 */
export const EVOLUTION: readonly { id: CreatureId; from: number }[] = [
  { id: "ajax",  from: 15000 },
  { id: "moth",  from: 6000 },
  { id: "crab",  from: 1500 },
  { id: "bug",   from: 500 },
  { id: "spore", from: 0 },
]

/** Редкие формы выдаются за поведение, а не за баллы — купить их нельзя. */
export const RARE: readonly CreatureId[] = ["jelly", "octo", "horn", "ghost", "squid", "sphinx"]

/** Текущая форма и сколько процентов до следующей. */
export function evolutionOf(lifetimePoints: number) {
  const index = EVOLUTION.findIndex((f) => lifetimePoints >= f.from)
  const current = EVOLUTION[index] ?? EVOLUTION[EVOLUTION.length - 1]!
  const next = index > 0 ? EVOLUTION[index - 1]! : null
  const span = next ? next.from - current.from : 0
  const progress = next && span > 0
    ? Math.min(100, Math.round(((lifetimePoints - current.from) / span) * 100))
    : 100
  return { current, next, progress, level: EVOLUTION.length - index }
}

